import { colorTokens, COLOR_TOKEN_NAMES, type ThemeName } from "./tokens";

const block = (theme: ThemeName, indent: string): string =>
  [
    `${indent}color-scheme: ${theme};`,
    ...COLOR_TOKEN_NAMES.map((n) => `${indent}--${n}: ${colorTokens[theme][n]};`),
  ].join("\n");

/**
 * Renders src/styles/tokens.css.
 *  - dark (default, brand-native): :root and [data-theme="dark"]
 *  - light: [data-theme="light"]
 *  - system: follows prefers-color-scheme; dark when the OS asks for dark or expresses no preference
 */
export function renderTokensCss(): string {
  return `/* GENERATED by scripts/tokens.ts from src/design/tokens.ts. DO NOT EDIT. Run \`npm run tokens:build\`. */
:root,
[data-theme="dark"] {
${block("dark", "  ")}
}

[data-theme="light"] {
${block("light", "  ")}
}

@media (prefers-color-scheme: light) {
  [data-theme="system"] {
${block("light", "    ")}
  }
}

@theme inline {
${COLOR_TOKEN_NAMES.map((n) => `  --color-${n}: var(--${n});`).join("\n")}
}
`;
}
