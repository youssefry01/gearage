/**
 * Keeps the generated part of docs/SEEDING.md in sync with the seed data: the list of specs the author is NOT sure
 * about (every `verify` entry in prisma/seed/data) and the catalog summary.
 *   npm run seed:docs         rewrites the generated block
 *   npm run seed:docs:check   fails if it is out of date (CI), like i18n:review:check
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadSeedData } from "../prisma/seed/data";
import { governorates, shippingZones } from "../prisma/seed/data/shipping-zones";
import { promoCodes } from "../prisma/seed/data/promo-codes";
import { branches } from "../prisma/seed/data/branches";

const START = "<!-- seed:generated:start -->";
const END = "<!-- seed:generated:end -->";
const cell = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");

const data = loadSeedData();
const flagged = data.products.filter((p) => p.verify);
const unflagged = data.products.filter((p) => !p.verify);
const brandName = (slug: string) => data.brands.find((b) => b.slug === slug)?.name ?? slug;

const perTop = new Map<string, { products: number; bundles: number }>();
for (const p of data.products) {
  const top = p.category.split("/")[0] as string;
  perTop.set(top, {
    products: (perTop.get(top)?.products ?? 0) + 1,
    bundles: perTop.get(top)?.bundles ?? 0,
  });
}
for (const b of data.bundles) {
  const top = b.category.split("/")[0] as string;
  perTop.set(top, {
    products: perTop.get(top)?.products ?? 0,
    bundles: (perTop.get(top)?.bundles ?? 0) + 1,
  });
}
const nameOfTop = (path: string) => data.categories.find((c) => c.path === path)?.name.en ?? path;

const summary = [
  "| Top-level category | Products | Bundles |",
  "| --- | ---: | ---: |",
  ...data.categories
    .filter((c) => !c.path.includes("/"))
    .map(
      (c) =>
        `| ${cell(nameOfTop(c.path))}${c.active === false ? " (inactive, reserved)" : ""} | ${perTop.get(c.path)?.products ?? 0} | ${perTop.get(c.path)?.bundles ?? 0} |`,
    ),
  `| **Total** | **${data.products.length}** | **${data.bundles.length}** |`,
].join("\n");

const flaggedTable = [
  "| SKU | Product | Verify these specs | Why |",
  "| --- | --- | --- | --- |",
  ...flagged.map(
    (p) =>
      `| \`${p.sku}\` | ${cell(`${brandName(p.brand)} ${p.model}`)} | ${(p.verify?.keys ?? []).map((k) => `\`${k}\``).join(", ")} | ${cell(p.verify?.note ?? "")} |`,
  ),
].join("\n");

const block = `${START}
<!-- This block is GENERATED by \`npm run seed:docs\` from prisma/seed/data. Do not edit it by hand. -->

### What the seed contains

${summary}

${data.categories.length} categories, ${data.brands.length} brands, ${data.tags.length} tags, ${Object.values(data.specDefinitions).reduce((n, d) => n + d.length, 0)} spec definitions across ${Object.keys(data.specDefinitions).length} categories.
Data-only files (validated, inserted when their tables ship): ${governorates.length} governorates in ${shippingZones.length} shipping zones, ${promoCodes.length} sample promo codes, ${branches.length} sample branches.

### Specs to verify (${flagged.length} of ${data.products.length} products flagged)

Every spec was written from the author's knowledge, not copied from a datasheet. The products below carry specs the author is
**not sure about**: confirm them on the manufacturer's page before trusting the compatibility badge or a spec filter. This is
a list of KNOWN doubt, not a certificate: the ${unflagged.length} unflagged products (${unflagged.map((p) => `\`${p.sku}\``).join(", ")}) are believed correct but are also unverified.

${flaggedTable}
${END}`;

const target = resolve(process.cwd(), "docs/SEEDING.md");
const current = readFileSync(target, "utf8");
const a = current.indexOf(START);
const b = current.indexOf(END);
if (a === -1 || b === -1) {
  console.error(`docs/SEEDING.md must contain ${START} and ${END}`);
  process.exit(1);
}
const next = current.slice(0, a) + block + current.slice(b + END.length);

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("docs/SEEDING.md is out of date. Run `npm run seed:docs` and commit the result.");
    process.exit(1);
  }
  console.log(`docs/SEEDING.md is up to date (${flagged.length} flagged products)`);
} else {
  writeFileSync(target, next);
  console.log(`wrote the generated block of docs/SEEDING.md (${flagged.length} flagged products)`);
}
