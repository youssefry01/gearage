export type Counts = { created: number; updated: number; unchanged: number };
const ENTITIES = [
  "categories",
  "brands",
  "tags",
  "specDefinitions",
  "products",
  "bundles",
  "productTags",
  "images",
  "showcaseBlocks",
  "bundleItems",
  "inventory",
] as const;
export type SeedEntity = (typeof ENTITIES)[number];
export type SeedReport = { entities: Record<SeedEntity, Counts>; assetsWritten: number };

const emptyReport = (): SeedReport => ({
  entities: Object.fromEntries(
    ENTITIES.map((e) => [e, { created: 0, updated: 0, unchanged: 0 }]),
  ) as Record<SeedEntity, Counts>,
  assetsWritten: 0,
});

/** Total rows the run created or updated. 0 means the database already matched the seed data. */
export const changesIn = (report: SeedReport): number =>
  Object.values(report.entities).reduce((n, c) => n + c.created + c.updated, 0);

export type SeedOptions = {
  /** Where the generated placeholder images are written (local disk for development). */
  storage: StorageProvider;
  /** Environment used for the local-database guard. Defaults to process.env. */
  env?: Readonly<Record<string, string | undefined>>;
  /** Replace the data (tests). Defaults to the per-category data files. */
  data?: SeedData;
};

const TX_OPTIONS = { maxWait: 20_000, timeout: 180_000 } as const;
const jsonOrNull = (v: unknown) =>
  v === null || v === undefined ? Prisma.DbNull : (v as Prisma.InputJsonValue);
const nul = <T>(v: T | undefined): T | null => (v === undefined ? null : v);

/** Whether every desired field already holds in the existing row (deep equality, so JSON key order never matters). */
function matches(existing: Record<string, unknown>, desired: Record<string, unknown>): boolean {
  return Object.keys(desired).every((k) =>
    isDeepStrictEqual(existing[k] ?? null, desired[k] ?? null),
  );
}

function count(report: SeedReport, entity: SeedEntity, kind: keyof Counts) {
  report.entities[entity][kind] += 1;
}

const CREDIT_PLACEHOLDER = "Generated placeholder";
const LICENSE_PLACEHOLDER =
  "Sample artwork generated by the seed script; not manufacturer material. Replace with official media-kit content (docs/ASSETS.md).";
const CREDIT_VIDEO = "Blender Foundation, Big Buck Bunny (CC BY 3.0)";
const LICENSE_VIDEO =
  "Open-licence film embedded only to test the video block layout. Replace with the manufacturer's official video.";

function showcaseRows(sku: string, blocks: readonly ShowcaseSeed[]) {
  return blocks.map((b, i) => {
    const base = {
      type: b.type,
      sortOrder: i,
      imageKey: null as string | null,
      imageAltEn: null as string | null,
      imageAltAr: null as string | null,
      titleEn: null as string | null,
      titleAr: null as string | null,
      bodyEn: null as string | null,
      bodyAr: null as string | null,
      captionEn: null as string | null,
      captionAr: null as string | null,
      videoUrl: null as string | null,
      credit: b.type === "VIDEO" ? CREDIT_VIDEO : CREDIT_PLACEHOLDER,
      licenseNote: b.type === "VIDEO" ? LICENSE_VIDEO : LICENSE_PLACEHOLDER,
    };
    const caption = (c?: Localized) => ({ captionEn: c?.en ?? null, captionAr: c?.ar ?? null });
    switch (b.type) {
      case "IMAGE":
        return {
          ...base,
          imageKey: keys.showcase(sku, i + 1),
          imageAltEn: b.alt.en,
          imageAltAr: b.alt.ar,
          ...caption(b.caption),
        };
      case "IMAGE_TEXT":
        return {
          ...base,
          imageKey: keys.showcase(sku, i + 1),
          imageAltEn: b.alt.en,
          imageAltAr: b.alt.ar,
          titleEn: b.title.en,
          titleAr: b.title.ar,
          bodyEn: b.body.en,
          bodyAr: b.body.ar,
          ...caption(b.caption),
        };
      case "FEATURE":
        return {
          ...base,
          titleEn: b.title.en,
          titleAr: b.title.ar,
          bodyEn: b.body.en,
          bodyAr: b.body.ar,
        };
      case "VIDEO":
        return { ...base, videoUrl: b.videoUrl, ...caption(b.caption) };
    }
  });
}

type Ctx = {
  tx: Tx;
  report: SeedReport;
  data: SeedData;
  categoryIds: Map<string, string>;
  brandIds: Map<string, string>;
  tagIds: Map<string, string>;
  productIds: Map<string, string>;
};

async function syncCategories({ tx, report, data, categoryIds }: Ctx) {
  const siblingIndex = new Map<string | null, number>();
  for (const c of data.categories) {
    const parentPath = categoryParentPath(c);
    const order = siblingIndex.get(parentPath) ?? 0;
    siblingIndex.set(parentPath, order + 1);
    const desired = {
      slug: categorySlug(c),
      depth: categoryDepth(c),
      parentId: parentPath ? (categoryIds.get(parentPath) ?? null) : null,
      nameEn: c.name.en,
      nameAr: c.name.ar,
      descriptionEn: c.description?.en ?? null,
      descriptionAr: c.description?.ar ?? null,
      imageKey: keys.category(c.path),
      sortOrder: order,
      isActive: c.active !== false,
    };
    const existing = await tx.category.findUnique({ where: { path: c.path } });
    if (!existing) {
      const row = await tx.category.create({ data: { path: c.path, ...desired } });
      categoryIds.set(c.path, row.id);
      count(report, "categories", "created");
    } else {
      categoryIds.set(c.path, existing.id);
      if (matches(existing, desired)) count(report, "categories", "unchanged");
      else {
        await tx.category.update({ where: { id: existing.id }, data: desired });
        count(report, "categories", "updated");
      }
    }
  }
}

async function syncBrands({ tx, report, data, brandIds }: Ctx) {
  for (const [i, b] of data.brands.entries()) {
    const desired = {
      nameEn: b.name,
      nameAr: null,
      websiteUrl: b.website ?? null,
      logoKey: keys.brand(b.slug),
      sortOrder: i,
      isActive: true,
    };
    const existing = await tx.brand.findUnique({ where: { slug: b.slug } });
    if (!existing) {
      brandIds.set(b.slug, (await tx.brand.create({ data: { slug: b.slug, ...desired } })).id);
      count(report, "brands", "created");
    } else {
      brandIds.set(b.slug, existing.id);
      if (matches(existing, desired)) count(report, "brands", "unchanged");
      else {
        await tx.brand.update({ where: { id: existing.id }, data: desired });
        count(report, "brands", "updated");
      }
    }
  }
}

async function syncTags({ tx, report, data, tagIds }: Ctx) {
  for (const tg of data.tags) {
    const desired = { nameEn: tg.name.en, nameAr: tg.name.ar };
    const existing = await tx.tag.findUnique({ where: { slug: tg.slug } });
    if (!existing) {
      tagIds.set(tg.slug, (await tx.tag.create({ data: { slug: tg.slug, ...desired } })).id);
      count(report, "tags", "created");
    } else {
      tagIds.set(tg.slug, existing.id);
      if (matches(existing, desired)) count(report, "tags", "unchanged");
      else {
        await tx.tag.update({ where: { id: existing.id }, data: desired });
        count(report, "tags", "updated");
      }
    }
  }
}

async function syncSpecDefinitions({ tx, report, data, categoryIds }: Ctx) {
  for (const [path, defs] of Object.entries(data.specDefinitions)) {
    const categoryId = categoryIds.get(path);
    if (!categoryId) throw new Error(`spec definitions: category "${path}" was not seeded`);
    for (const [i, d] of (defs as readonly SpecDef[]).entries()) {
      const desired = {
        type: d.type,
        unit: d.unit ?? null,
        labelEn: d.labelEn,
        labelAr: d.labelAr,
        filterable: d.filterable,
        facet: d.facet,
        required: d.required,
        options: d.options ?? null,
        minValue: d.minValue ?? null,
        maxValue: d.maxValue ?? null,
        sortOrder: i,
      };
      const write = { ...desired, options: jsonOrNull(desired.options) };
      const existing = await tx.specDefinition.findUnique({
        where: { categoryId_key: { categoryId, key: d.key } },
      });
      if (!existing) {
        await tx.specDefinition.create({ data: { categoryId, key: d.key, ...write } });
        count(report, "specDefinitions", "created");
      } else if (matches(existing, desired)) count(report, "specDefinitions", "unchanged");
      else {
        await tx.specDefinition.update({ where: { id: existing.id }, data: write });
        count(report, "specDefinitions", "updated");
      }
    }
  }
}

/** Replaces a product's child rows only when they differ from the seed (so an unchanged run writes nothing). */
async function syncChildren(
  ctx: Ctx,
  productId: string,
  input: {
    sku: string;
    title: Localized;
    tags: readonly string[];
    showcase?: readonly ShowcaseSeed[];
  },
) {
  const { tx, report, tagIds } = ctx;

  // images
  const imageRows = Array.from({ length: PRODUCT_IMAGE_COUNT }, (_, i) => ({
    storageKey: keys.product(input.sku, i + 1),
    altEn: `${input.title.en} (illustrative placeholder, ${i === 0 ? "product view" : "key specifications"})`,
    altAr: `${input.title.ar} (صورة توضيحية مؤقتة، ${i === 0 ? "عرض المنتج" : "أهم المواصفات"})`,
    width: i < 2 ? 800 : null,
    height: i < 2 ? 800 : null,
    sortOrder: i,
  }));
  const images = await tx.productImage.findMany({
    where: { productId },
    orderBy: { sortOrder: "asc" },
  });
  const sameImages =
    images.length === imageRows.length &&
    images.every((row, i) => matches(row, imageRows[i] as Record<string, unknown>));
  if (sameImages) count(report, "images", "unchanged");
  else {
    await tx.productImage.deleteMany({ where: { productId } });
    await tx.productImage.createMany({ data: imageRows.map((r) => ({ productId, ...r })) });
    count(report, "images", images.length === 0 ? "created" : "updated");
  }

  // showcase blocks
  const blockRows = showcaseRows(input.sku, input.showcase ?? []);
  const blocks = await tx.showcaseBlock.findMany({
    where: { productId },
    orderBy: { sortOrder: "asc" },
  });
  const sameBlocks =
    blocks.length === blockRows.length &&
    blocks.every((row, i) => matches(row, blockRows[i] as Record<string, unknown>));
  if (sameBlocks) {
    if (blockRows.length > 0) count(report, "showcaseBlocks", "unchanged");
  } else {
    await tx.showcaseBlock.deleteMany({ where: { productId } });
    if (blockRows.length > 0)
      await tx.showcaseBlock.createMany({ data: blockRows.map((r) => ({ productId, ...r })) });
    count(report, "showcaseBlocks", blocks.length === 0 ? "created" : "updated");
  }

  // tags
  const wanted = new Set(input.tags.map((s) => tagIds.get(s) as string));
  const have = new Set(
    (await tx.productTag.findMany({ where: { productId } })).map((r) => r.tagId),
  );
  const add = [...wanted].filter((id) => !have.has(id));
  const drop = [...have].filter((id) => !wanted.has(id));
  if (add.length === 0 && drop.length === 0) count(report, "productTags", "unchanged");
  else {
    if (drop.length > 0)
      await tx.productTag.deleteMany({ where: { productId, tagId: { in: drop } } });
    if (add.length > 0)
      await tx.productTag.createMany({ data: add.map((tagId) => ({ productId, tagId })) });
    count(report, "productTags", have.size === 0 ? "created" : "updated");
  }
}

async function syncPhysical(ctx: Ctx, p: SeedProduct) {
  const { tx, report, data, categoryIds, brandIds, productIds } = ctx;
  const defs = resolveSpecDefinitions<SpecDef>(p.category, data.specDefinitions);
  void defs; // validated before any write (assertValidSeedData)
  const desired = {
    type: "PHYSICAL" as const,
    status: "ACTIVE" as const,
    slug: productSlug(p),
    mpn: nul(p.mpn),
    brandId: brandIds.get(p.brand) as string,
    modelName: p.model,
    categoryId: categoryIds.get(p.category) as string,
    titleEn: p.title.en,
    titleAr: p.title.ar,
    shortDescriptionEn: p.short.en,
    shortDescriptionAr: p.short.ar,
    descriptionEn: p.description?.en ?? null,
    descriptionAr: p.description?.ar ?? null,
    condition: "NEW" as const,
    price: priceOf(p),
    compareAtPrice: compareAtOf(p),
    cost: costOf(p),
    taxClass: "STANDARD" as const,
    lowStockThreshold: p.lowStockThreshold ?? 3,
    warrantyMonths: p.warrantyMonths,
    weightGrams: nul(p.weightGrams),
    lengthMm: nul(p.lengthMm),
    widthMm: nul(p.widthMm),
    heightMm: nul(p.heightMm),
    specs: p.specs,
    bundlePricingMode: null,
    bundleDiscountBps: null,
    bundleDiscountAmount: null,
  };
  const existing = await tx.product.findFirst({ where: { sku: p.sku, deletedAt: null } });
  let id: string;
  if (!existing) {
    id = (
      await tx.product.create({
        data: {
          ...desired,
          sku: p.sku,
          specs: p.specs,
          viewCount: p.views,
          unitsSold: p.sold,
          createdAt: createdAtFor(p.addedDaysAgo),
        },
      })
    ).id;
    count(report, "products", "created");
  } else {
    id = existing.id;
    if (matches(existing, desired)) count(report, "products", "unchanged");
    else {
      await tx.product.update({ where: { id }, data: desired });
      count(report, "products", "updated");
    }
  }
  productIds.set(p.sku, id);
  await syncChildren(ctx, id, { sku: p.sku, title: p.title, tags: p.tags, showcase: p.showcase });

  // Stock is created ONCE. Re-seeding never resets it, so sales and adjustments made since survive.
  const inventory = await tx.inventory.findUnique({ where: { productId: id } });
  if (inventory) count(report, "inventory", "unchanged");
  else {
    if (p.stock > 0)
      await restockUnits(
        [{ productId: id, quantity: p.stock }],
        { reason: "RECEIVED", note: "Seed: initial stock" },
        { tx },
      );
    else await tx.inventory.create({ data: { productId: id, onHand: 0 } });
    count(report, "inventory", "created");
  }
}

async function syncBundle(ctx: Ctx, b: SeedBundle) {
  const { tx, report, categoryIds, productIds } = ctx;
  const desired = {
    type: "BUNDLE" as const,
    status: "ACTIVE" as const,
    slug: productSlug(b),
    mpn: null,
    brandId: null,
    modelName: null,
    categoryId: categoryIds.get(b.category) as string,
    titleEn: b.title.en,
    titleAr: b.title.ar,
    shortDescriptionEn: b.short.en,
    shortDescriptionAr: b.short.ar,
    descriptionEn: b.description.en,
    descriptionAr: b.description.ar,
    condition: "NEW" as const,
    price: fromPounds(b.fixedPriceEgp),
    compareAtPrice: null,
    cost: null,
    taxClass: "STANDARD" as const,
    lowStockThreshold: 3,
    warrantyMonths: b.warrantyMonths,
    specs: b.specs,
    bundlePricingMode: "FIXED" as const,
    bundleDiscountBps: null,
    bundleDiscountAmount: null,
  };
  const existing = await tx.product.findFirst({ where: { sku: b.sku, deletedAt: null } });
  let id: string;
  if (!existing) {
    id = (
      await tx.product.create({
        data: {
          ...desired,
          sku: b.sku,
          viewCount: b.views,
          unitsSold: b.sold,
          createdAt: createdAtFor(b.addedDaysAgo),
        },
      })
    ).id;
    count(report, "bundles", "created");
  } else {
    id = existing.id;
    if (matches(existing, desired)) count(report, "bundles", "unchanged");
    else {
      await tx.product.update({ where: { id }, data: desired });
      count(report, "bundles", "updated");
    }
  }
  productIds.set(b.sku, id);
  await syncChildren(ctx, id, { sku: b.sku, title: b.title, tags: b.tags, showcase: b.showcase });

  // Composition is owned by the seed: add, change and remove so the bundle always equals the data file.
  const wanted = b.items.map((item, i) => ({
    componentId: productIds.get(item.sku) as string,
    quantity: item.quantity ?? 1,
    swappable: false,
    sortOrder: i,
  }));
  const have = await tx.bundleItem.findMany({ where: { bundleId: id } });
  for (const row of have) {
    if (!wanted.some((w) => w.componentId === row.componentId)) {
      await tx.bundleItem.delete({
        where: { bundleId_componentId: { bundleId: id, componentId: row.componentId } },
      });
      count(report, "bundleItems", "updated");
    }
  }
  for (const w of wanted) {
    const row = have.find((h) => h.componentId === w.componentId);
    if (!row) {
      await tx.bundleItem.create({ data: { bundleId: id, ...w } });
      count(report, "bundleItems", "created");
    } else if (matches(row, w)) count(report, "bundleItems", "unchanged");
    else {
      await tx.bundleItem.update({
        where: { bundleId_componentId: { bundleId: id, componentId: w.componentId } },
        data: w,
      });
      count(report, "bundleItems", "updated");
    }
  }
}

/**
 * Seeds the catalog: categories, spec definitions, brands, tags, products, bundles, stock and placeholder images.
 * Idempotent: every row is matched on a natural key (path, slug, SKU) and written only when it differs, so a second run
 * changes nothing (same ids, same updatedAt). Stock and the view/sold counters are set when a row is created and never
 * touched again. The seed only adds and updates, it never deletes. Catalog data only: no users, orders or reviews.
 */
export async function runSeed(options: SeedOptions): Promise<SeedReport> {
  assertLocalDatabaseForSeed(options.env ?? process.env);
  const data = options.data ?? loadSeedData();
  assertValidSeedData(data);

  const report = emptyReport();
  for (const asset of allPlaceholderAssets(data)) {
    await options.storage.put({
      key: asset.key,
      body: new TextEncoder().encode(asset.svg),
      contentType: "image/svg+xml",
      overwrite: true,
    });
    report.assetsWritten += 1;
  }

  await getDb().$transaction(async (tx) => {
    const ctx: Ctx = {
      tx,
      report,
      data,
      categoryIds: new Map(),
      brandIds: new Map(),
      tagIds: new Map(),
      productIds: new Map(),
    };
    await syncCategories(ctx);
    await syncSpecDefinitions(ctx);
    await syncBrands(ctx);
    await syncTags(ctx);
    for (const p of data.products) await syncPhysical(ctx, p);
    for (const b of data.bundles) await syncBundle(ctx, b);
  }, TX_OPTIONS);

  return report;
}
